// Generate 90 days of Search Metrics
export function generate90DaysSearchMetrics(): DailySearchMetric[] {
  const metrics: DailySearchMetric[] = [];
  const today = new Date();

  for (let i = 89; i >= 0; i--) {
    const d = new Date(today);
    d.setDate(d.getDate() - i);
    const dateStr = d.toISOString().split("T")[0];

    // Growth progression factor over 90 days
    const progress = 1 + (90 - i) * 0.0035;
    const dayOfWeek = d.getDay();
    const weekendFactor = (dayOfWeek === 0 || dayOfWeek === 6) ? 0.75 : 1.1;
    const noise = 0.92 + ((i * 13) % 17) / 100;

    const gscImpressions = Math.round(14500 * progress * weekendFactor * noise);
    const gscClicks = Math.round(720 * progress * weekendFactor * noise);
    const gscCtr = Math.round((gscClicks / gscImpressions) * 1000) / 10;
    const gscAveragePosition = Math.round((14.8 - (90 - i) * 0.04 + ((i % 5) * 0.1)) * 10) / 10;

    const ga4Sessions = Math.round(1850 * progress * weekendFactor * noise);
    const ga4Conversions = Math.round(68 * progress * weekendFactor * noise);
    const ga4BounceRate = Math.round((42.5 - (90 - i) * 0.03 + ((i % 7) * 0.2)) * 10) / 10;

    const gbpViews = Math.round(420 * progress * noise);
    const gbpSearches = Math.round(310 * progress * noise);
    const gbpCalls = Math.round(18 * progress * weekendFactor * noise);
    const gbpDirections = Math.round(24 * progress * weekendFactor * noise);

    metrics.push({
      date: dateStr,
      gscImpressions,
      gscClicks,
      gscCtr,
      gscAveragePosition,
      ga4Sessions,
      ga4Conversions,
      ga4BounceRate,
      gbpViews,
      gbpSearches,
      gbpCalls,
      gbpDirections,
    });
  }

  return metrics;
}

